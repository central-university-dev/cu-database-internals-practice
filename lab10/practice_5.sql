-- ============================================================
-- Практика 5. MVCC и VACUUM: очистка мёртвых версий
-- Необходимо:
--   • увидеть, что UPDATE создаёт много старых версий, которые не исчезают,
--   • понять, что VACUUM удаляет только те версии, которые больше никому не могут быть видимы,
--   • изучить, как меняется физическая страница после VACUUM,
--   • научиться интерпретировать t_xmin/t_xmax и line pointers «до» и «после».
-- ============================================================


-- --------------------------------------------
-- 1. Создадим много старых версий одной строки
-- --------------------------------------------

-- Чтобы получилась цепочка старых версий id = 6:
UPDATE bank_accounts SET balance = balance + 1 WHERE id = 6;
UPDATE bank_accounts SET balance = balance + 2 WHERE id = 6;
UPDATE bank_accounts SET balance = balance + 3 WHERE id = 6;
UPDATE bank_accounts SET balance = balance + 4 WHERE id = 6;
UPDATE bank_accounts SET balance = balance + 5 WHERE id = 6;

-- На этом этапе в heap существует несколько физических строк (версий) для id = 6.


-- --------------------------------------------
-- 2. Изучаем физическую страницу до VACUUM
-- --------------------------------------------

SELECT lp, t_xmin, t_xmax, t_ctid
FROM heap_page_items(get_raw_page('bank_accounts', 0))
ORDER BY lp;

-- Вопросы:
--   1) Сколько физических версий строки id=6 вы видите?
--   2) Какие из них имеют ненулевой xmax?
--   3) Как выглядит цепочка ctid?
--   4) Почему все эти версии до сих пор лежат на странице, хотя логически строка только одна?


-- --------------------------------------------
-- 3. Запускаем обычный VACUUM
-- --------------------------------------------

VACUUM bank_accounts;

-- Пояснение:
--   VACUUM:
--     • удаляет (mark as reusable) версии, которые больше не нужны ни одной транзакции,
--     • освобождает line pointers, но НЕ обязательно уплотняет страницу полностью,
--     • НЕ удаляет все старые версии, если они всё ещё потенциально могут быть нужны читателям.


-- --------------------------------------------
-- 4. Смотрим страницу после VACUUM
-- --------------------------------------------

SELECT lp, t_xmin, t_xmax, t_ctid
FROM heap_page_items(get_raw_page('bank_accounts', 0))
ORDER BY lp;

-- Вопросы:
--   1) Какие строки исчезли? Какие остались?
--   2) Почему VACUUM удалил только некоторые версии?
--   3) Есть ли теперь "дыры" среди lp (line pointers)?
--   4) Что это означает: физическое удаление и логическое удаление — разные вещи?


-- --------------------------------------------
-- 5. Теперь запускаем VACUUM FULL (осторожно, он блокирует таблицу)
-- --------------------------------------------

VACUUM FULL bank_accounts;

-- Пояснение:
--   В отличие от обычного VACUUM,
--   VACUUM FULL переписывает таблицу заново, создавая новый heap-файл.
--   Все старые версии исчезают полностью, страница становится компактной.


-- --------------------------------------------
-- 6. Смотрим страницу после VACUUM FULL
-- --------------------------------------------

SELECT lp, t_xmin, t_xmax, t_ctid
FROM heap_page_items(get_raw_page('bank_accounts', 0))
ORDER BY lp;

