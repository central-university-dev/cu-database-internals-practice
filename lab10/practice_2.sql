-- ============================================================
-- Практика 2. MVCC под микроскопом: физические версии строк
-- Необходимо:
--   • понять, что UPDATE не "изменяет" строку, а создаёт НОВУЮ версию,
--   • увидеть, как меняются tuple header (xmin, xmax, ctid),
--   • изучить одновременное существование нескольких версий в heap,
--   • научиться соотносить логическую строку и физические версии.
-- ============================================================


-- --------------------------------------------
-- 1. SESSION A: создаём обновление, но НЕ делаем COMMIT
-- --------------------------------------------

BEGIN;
UPDATE bank_accounts SET balance = balance - 100 WHERE id = 1;

-- Пояснение:
--   UPDATE делает:
--     (а) СТАРУЮ версию — "убитой" (ставит xmax = XID текущей транзакции),
--     (б) создаёт НОВУЮ версию с новым xmin,
--     (в) обновляет ctid у старой строки (указывает на новую).


-- --------------------------------------------
-- 2. SUPERUSER: изучаем физическую страницу ПОСЛЕ UPDATE, но ДО COMMIT
-- --------------------------------------------

-- Важно: нужно определить lp (line pointer), соответствующий id = 1.
-- Он может быть разным в зависимости от окружения,
-- поэтому сначала найдите строку:
SELECT lp, t_xmin, t_xmax, t_ctid
FROM heap_page_items(get_raw_page('bank_accounts', 0));

-- Затем повторите запрос, фильтруя по соответствующему lp:
-- Например:
-- SELECT * FROM heap_page_items(get_raw_page('bank_accounts', 0)) WHERE lp = 1;


-- Вопросы:
--   1) Где теперь хранится старая версия строки id=1?
--   2) Как изменился её t_xmax? Почему xmax ≠ 0?
--   3) Как выглядит новая версия? Какое у неё xmin?
--   4) Как ctid у старой версии указывает на новую?
--   5) Почему физически теперь существует две строки, хотя id — один?


-- --------------------------------------------
-- 3. SESSION A выполняет COMMIT
-- --------------------------------------------

COMMIT;

-- Пояснение:
--   COMMIT делает транзакцию окончательной,
--   но НЕ удаляет старую версию строки:
--   она остаётся в heap как «невидимая» для будущих транзакций.


-- --------------------------------------------
-- 4. SUPERUSER: снова изучаем страницу ПОСЛЕ COMMIT
-- --------------------------------------------

SELECT lp, t_xmin, t_xmax, t_ctid
FROM heap_page_items(get_raw_page('bank_accounts', 0));

-- Вопросы:
--   1) Что изменилось между состоянием «до COMMIT» и «после COMMIT»?
--   2) Существует ли старая версия? Что у неё в t_xmax?
--   3) Видите ли вы, что новая версия — единственная «живая»?
--   4) Почему PostgreSQL не удаляет старую версию немедленно?
--   5) Какое свойство модели MVCC объясняет необходимость хранить обе версии?


-- --------------------------------------------
-- 5. Дополнительное исследование: создайте ещё одно обновление
-- --------------------------------------------

