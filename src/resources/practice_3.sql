-- --------------------------------------------
-- 1. Инициализация данных
--    Создаём таблицу people с "кривым" распределением:
--    50% строк имеют age = 25, остальные — случайные значения.
-- --------------------------------------------

DROP TABLE IF EXISTS people;

CREATE TABLE people (
                        id serial PRIMARY KEY,
                        age int
);

INSERT INTO people(age)
SELECT
    CASE
        WHEN random() < 0.5 THEN 25                       -- 50% строк
        ELSE floor(random()*100)::int                     -- остальные 0..99
END
FROM generate_series(1, 400000);

-- Индекс по age (чтобы показать работу IndexScan / BitmapScan)
CREATE INDEX people_age_idx ON people(age);

-- Обновляем статистику
ANALYZE people;


-- --------------------------------------------
-- 2. Смотрим статистику колонки age
--    pg_stats — человекочитаемый слой над pg_statistic.
-- --------------------------------------------

-- Посмотреть всю статистику по колонке age:
SELECT *
FROM pg_stats
WHERE tablename = 'people'
  AND attname = 'age';

-- Что хотим увидеть в результатах:
--   • n_distinct          — сколько уникальных значений (оценка)
--   • most_common_vals    — какие значения встречаются чаще всего
--   • most_common_freqs   — частоты этих значений
--   • histogram_bounds    — границы гистограммы оставшихся значений
--   • correlation         — корреляция порядка значений с физическим порядком строк


-- --------------------------------------------
-- 3. Проверяем план ДО порчи статистики
--    age = 25 встречается в ~50% строк → селективность низкая
--    SeqScan или BitmapHeapScan — правильное решение.
-- --------------------------------------------

EXPLAIN SELECT * FROM people WHERE age = 25;


-- --------------------------------------------
-- 4. Портим статистику
--    Устанавливаем минимальный объём выборки — PostgreSQL
--    возьмёт очень мало данных при ANALYZE.
-- --------------------------------------------

ALTER TABLE people ALTER COLUMN age SET STATISTICS 1;
ANALYZE people;

-- Теперь в pg_stats вы увидите:
--   • пропали most_common_vals
--   • неверные частоты most_common_freqs
--   • маленький n_distinct
--   • искажённая correlation
--
-- PostgreSQL будет думать, что age=25 встречается очень редко.


-- --------------------------------------------
-- 5. Проверяем план ПОСЛЕ порчи статистики
--    Теперь оптимизатор считает, что age=25 — селективный фильтр.
--    PLAN станет IndexScan или Bitmap Index Scan.
-- --------------------------------------------

EXPLAIN SELECT * FROM people WHERE age = 25;

-- Это неверно, так как 50% строк соответствуют условию.
-- Но оптимизатор опирается только на статистику, а не на реальные данные.


