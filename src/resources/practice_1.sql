-- ============================================================
-- Практика 1. SeqScan vs IndexScan (селективность)
-- Демонстрация того, как селективность влияет на выбор плана.
-- ============================================================

-- --------------------------------------------
-- 1. Инициализация данных
-- --------------------------------------------

DROP TABLE IF EXISTS users;

CREATE TABLE users (
                       id serial PRIMARY KEY,
                       age int,
                       name text
);

-- Наполняем таблицу 100 000 строками, возраст равномерно 0..100
INSERT INTO users(age, name)
SELECT (random()*100)::int, md5(random()::text)
FROM generate_series(1, 100000);

-- Удаляем индекс, если он существовал
DROP INDEX IF EXISTS users_age_idx;


-- --------------------------------------------
-- 2. Задание: анализ селективности без индекса
-- --------------------------------------------

-- Выборка очень широкая: условие age > 5 оставляет много строк,
-- поэтому SeqScan, как правило, выгоднее.
EXPLAIN SELECT * FROM users WHERE age > 5;

-- Выборка узкая: age > 90 оставляет мало строк,
-- но без индекса SeqScan всё равно единственный доступный план.
EXPLAIN SELECT * FROM users WHERE age > 90;


-- --------------------------------------------
-- 3. Создаём индекс по age
-- --------------------------------------------

CREATE INDEX users_age_idx ON users(age);

-- Обновляем статистику
ANALYZE users;


-- --------------------------------------------
-- 4. Задание: анализ селективности с индексом
-- --------------------------------------------

-- При широкой выборке (мало селективной),
-- SeqScan чаще всего остаётся выгодным.
EXPLAIN SELECT * FROM users WHERE age > 5;

-- При узкой выборке (высокоселективной),
-- оптимизатор выберет IndexScan (или BitmapScan).
EXPLAIN SELECT * FROM users WHERE age > 90;
